import { test,expect } from "@playwright/experimental-ct-react";
import { IntegrationHarness } from "./Harness";

/** Only delivery is fault-injected: actual commands commit through Next, Go and PostgreSQL. */
test("private topics and labels recover committed responses without books or journals",async({mount,page})=>{
  await page.setViewportSize({width:390,height:844});
  let component=await mount(<IntegrationHarness/>);
  await page.getByRole("button",{name:"All transactions",exact:true}).click();
  await expect(page.getByText("Fictional cafe purchase",{exact:true})).toBeVisible();
  await expect(page.getByText("Fictional euro purchase",{exact:true})).toBeVisible();
  const headers={Authorization:"Bearer synthetic.browser.proof",Origin:new URL(page.url()).origin};
  const discovery=await page.request.get(new URL("/v1/collection",page.url()).href,{headers});
  expect(discovery.status()).toBe(200);
  const workspace=(await discovery.json()).workspace_id;
  const base=`/v1/collections/${workspace}`;
  expect((await page.request.get(new URL(base+"/taxonomy",page.url()).href,{headers:{...headers,Authorization:"Bearer synthetic.other.proof"}})).status()).toBe(404);
  expect((await page.request.get(new URL(base+"/taxonomy",page.url()).href,{headers:{...headers,Origin:"https://foreign.invalid"}})).status()).toBe(403);
  const catalog=await (await page.request.get(new URL(base+"/taxonomy",page.url()).href,{headers})).json();
  expect(catalog.topics).toEqual([]);
  await page.getByText("Manage topics",{exact:true}).click();
  await page.getByRole("button",{name:"Add topic",exact:true}).click();
  await page.getByLabel("Topic 1 name",{exact:true}).fill("Fictional Food");
  await page.getByRole("button",{name:"Preview topic changes",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Review topic changes",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Save topic review",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Saved topic review",exact:true})).toBeVisible();
  let taxonomyExecutions=0;
  await page.route("**/v1/collections/*/label-commands/*/execute",async route=>{
    taxonomyExecutions++;
    const response=await route.fetch();
    expect(response.status()).toBe(200);
    expect((await response.json()).command.state).toBe("committed");
    await route.abort("failed");
  });
  await page.getByRole("button",{name:"Confirm topic changes",exact:true}).click();
  await expect.poll(()=>taxonomyExecutions).toBe(1);
  await component.unmount();
  await page.unroute("**/v1/collections/*/label-commands/*/execute");
  component=await mount(<IntegrationHarness/>);
  await expect(page.getByText("Topics updated. No journal was created.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Acknowledge result",exact:true}).click();
  expect(taxonomyExecutions).toBe(1);
  await expect(page.getByText("Fictional cafe purchase",{exact:true})).toBeVisible();
  const cafe=page.getByRole("listitem").filter({hasText:"Fictional cafe purchase"});
  await cafe.getByRole("checkbox").check();
  await page.getByLabel("Label selected transactions",{exact:true}).selectOption({label:"Fictional Food"});
  await page.getByRole("button",{name:"Preview labels for 1 selected",exact:true}).click();
  await page.getByRole("button",{name:"Save label review",exact:true}).click();
  let labelExecutions=0;
  await page.route("**/v1/collections/*/label-commands/*/execute",async route=>{
    labelExecutions++;
    const response=await route.fetch();
    expect(response.status()).toBe(200);
    const receipt=await response.json();
    expect(receipt.command.state).toBe("committed");
    expect(receipt.command.preview.review_rows[0].money.amount).toBe("0.1");
    await route.abort("failed");
  });
  await page.getByRole("button",{name:"Confirm labels for 1 selected",exact:true}).click();
  await expect.poll(()=>labelExecutions).toBe(1);
  await component.unmount();
  await page.unroute("**/v1/collections/*/label-commands/*/execute");
  await mount(<IntegrationHarness/>);
  await expect(page.getByText("Labels applied. No journal was created.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Acknowledge result",exact:true}).click();
  expect(labelExecutions).toBe(1);
  await expect(page.getByText("Fictional cafe purchase",{exact:true})).toBeVisible();
  const currentCatalog=await(await page.request.get(new URL(base+"/taxonomy",page.url()).href,{headers})).json();
  const query={profile:"private-collection-review-v1",source_account_id:null,assignment:"all",starts_on:null,through_date:null,search:"",topic:{kind:"all"},sort:"date_desc",snapshot:null,cursor:null,limit:25};
  const result=await page.request.post(new URL(base+"/review/query",page.url()).href,{headers,data:query});
  expect(result.status()).toBe(200);
  const actual=await result.json();
  expect(actual.matching_count).toBe("4");
  expect(actual.partial).toBe(false);
  const food=actual.items.find((row:{description:string})=>row.description==="Fictional cafe purchase");
  expect(food.owner_topic).toEqual({state:"topic",topic_id:currentCatalog.topics[0].topic_id,name:"Fictional Food"});
  expect(actual.items.find((row:{description:string})=>row.description==="Fictional exact large quantity").money.amount).toBe("9007199254740993.01");
  expect(actual.items.find((row:{description:string})=>row.description==="Fictional euro purchase").money.numeric_code).toBeNull();
  expect(actual.items.find((row:{description:string})=>row.description==="Fictional unsupported quantity").money).toMatchObject({state:"held",reason:"unsupported_currency",amount:null});
  await page.screenshot({path:test.info().outputPath("fictional-private-labels-mobile.png"),fullPage:true});
});
