// Package staging provides private, synthetic-only local evidence storage.
// It grants no accounting authority and is not a hosted encrypted object store.
package staging

import (
	"bytes"
	"context"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"io"
	"os"
	"regexp"
	"sync"
	"time"
)

const MaxBytes = 1 << 20

var uuidPattern = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// Error is a bounded classification without an underlying source error or path.
type Error struct{ Code string }

// Error returns only the fixed safe code.
func (e *Error) Error() string { return e.Code }

// failure constructs a fixed storage outcome; private diagnostics are never wrapped.
func failure(code string) error { return &Error{code} }

// Scope contains server-owned book identity; upstream authorization remains mandatory.
type Scope struct{ EntityID, BookID string }

// Reference is generated by NewReference and retained by the future server-side batch record.
type Reference struct {
	Scope    Scope
	ObjectID string
}

// Receipt identifies exact retained bytes without disclosing a filesystem location.
type Receipt struct {
	Reference Reference
	ByteCount int
	SHA256    [32]byte
}

// Source transfers reader ownership to Put and must honor cancellation in both methods.
type Source interface {
	Read(context.Context, []byte) (int, error)
	Close(context.Context) error
}

// Store confines cooperative local callers to an already-private root directory.
type Store struct {
	root      *os.Root
	directory *os.File
	life      sync.RWMutex
	closed    bool
	fault     func(string) error
}

// validID rejects path syntax, noncanonical UUIDs and the reserved all-zero value.
func validID(s string) bool {
	return len(s) == 36 && uuidPattern.MatchString(s) && s != "00000000-0000-0000-0000-000000000000"
}

// validReference checks syntax only, never authorization or evidence ownership.
func validReference(r Reference) bool {
	return validID(r.Scope.EntityID) && validID(r.Scope.BookID) && validID(r.ObjectID)
}

// randomID generates names without caller-controlled path fragments.
func randomID() (string, error) {
	var b [16]byte
	if _, e := rand.Read(b[:]); e != nil {
		return "", failure("storage_error")
	}
	b[6] = (b[6] & 15) | 64
	b[8] = (b[8] & 63) | 128
	s := hex.EncodeToString(b[:])
	return s[:8] + "-" + s[8:12] + "-" + s[12:16] + "-" + s[16:20] + "-" + s[20:], nil
}

// NewReference generates an object identity under a previously authorized server scope.
func NewReference(scope Scope) (Reference, error) {
	if !validID(scope.EntityID) || !validID(scope.BookID) {
		return Reference{}, failure("invalid_reference")
	}
	id, e := randomID()
	if e != nil {
		return Reference{}, e
	}
	return Reference{scope, id}, nil
}

// Open pins an existing root descriptor after rejecting a symlink, wrong owner or permissive directory.
func Open(path string) (*Store, error) {
	if !supported {
		return nil, failure("unsupported_platform")
	}
	before, e := os.Lstat(path)
	if e != nil || !before.IsDir() || before.Mode().Perm() != 0700 || !owned(before) {
		return nil, failure("unsafe_storage")
	}
	root, e := os.OpenRoot(path)
	if e != nil {
		return nil, failure("unsafe_storage")
	}
	dir, e := root.Open(".")
	if e != nil {
		root.Close()
		return nil, failure("unsafe_storage")
	}
	after, e := dir.Stat()
	if e != nil || !os.SameFile(before, after) {
		dir.Close()
		root.Close()
		return nil, failure("unsafe_storage")
	}
	return &Store{root: root, directory: dir}, nil
}

// Close waits for active owned operations and then releases both pinned descriptors.
func (s *Store) Close() error {
	s.life.Lock()
	defer s.life.Unlock()
	if s.closed {
		return nil
	}
	s.closed = true
	e1 := s.directory.Close()
	e2 := s.root.Close()
	if e1 != nil || e2 != nil {
		return failure("storage_error")
	}
	return nil
}

// stem constructs only flat generated names; no caller URL or filename is accepted.
func stem(r Reference) string { return r.Scope.EntityID + "_" + r.Scope.BookID + "_" + r.ObjectID }

// checkContext bounds progression but cannot interrupt a kernel filesystem call.
func checkContext(ctx context.Context) error {
	if ctx.Err() != nil {
		return failure("cancelled")
	}
	return nil
}

// checkpoint supplies package-private deterministic test faults, never a runtime fault API.
func (s *Store) checkpoint(stage string) error {
	if s.fault != nil {
		if e := s.fault(stage); e != nil {
			return failure("storage_error")
		}
	}
	return nil
}

// syncDirectory acknowledges directory entries only after the filesystem sync succeeds.
func (s *Store) syncDirectory() error {
	if e := s.checkpoint("directory_sync"); e != nil {
		return e
	}
	if e := s.directory.Sync(); e != nil {
		return failure("storage_error")
	}
	return nil
}

// safeOpen checks both pathname and opened inode, rejects special files and never follows symlinks.
func (s *Store) safeOpen(name string, flags int) (*os.File, error) {
	before, e := s.root.Lstat(name)
	if e != nil {
		if errors.Is(e, os.ErrNotExist) {
			return nil, failure("not_found")
		}
		return nil, failure("unsafe_storage")
	}
	if !before.Mode().IsRegular() || before.Mode().Perm() != 0600 || !owned(before) {
		return nil, failure("unsafe_storage")
	}
	f, e := s.root.OpenFile(name, flags|noFollow|nonBlock, 0)
	if e != nil {
		return nil, failure("unsafe_storage")
	}
	after, e := f.Stat()
	if e != nil || !after.Mode().IsRegular() || after.Mode().Perm() != 0600 || !owned(after) || !os.SameFile(before, after) {
		f.Close()
		return nil, failure("unsafe_storage")
	}
	return f, nil
}

// create creates a private exclusive inode and rejects unusual permission/ownership results.
func (s *Store) create(name string) (*os.File, error) {
	f, e := s.root.OpenFile(name, os.O_CREATE|os.O_EXCL|os.O_RDWR|noFollow|nonBlock, 0600)
	if e != nil {
		return nil, e
	}
	info, e := f.Stat()
	if e != nil || !info.Mode().IsRegular() || info.Mode().Perm() != 0600 || !owned(info) {
		f.Close()
		return nil, failure("unsafe_storage")
	}
	return f, nil
}

// lock serializes cooperating processes using an immutable lock inode, never removing its name.
func (s *Store) lock(ctx context.Context, key string) (func(), error) {
	name := key + ".lock"
	f, e := s.create(name)
	if errors.Is(e, os.ErrExist) {
		f, e = s.safeOpen(name, os.O_RDWR)
	}
	if e != nil {
		return nil, failure("unsafe_storage")
	}
	if e = lockFile(ctx, f); e != nil {
		f.Close()
		return nil, e
	}
	return func() { _ = f.Close() }, nil
}

// isDeleted validates the permanent tombstone rather than treating arbitrary files as deletion authority.
func (s *Store) isDeleted(key string) (bool, error) {
	f, e := s.safeOpen(key+".deleted", os.O_RDONLY)
	if hasCode(e, "not_found") {
		return false, nil
	}
	if e != nil {
		return false, e
	}
	defer f.Close()
	info, e := f.Stat()
	if e != nil || info.Size() != 0 {
		return false, failure("unsafe_storage")
	}
	return true, nil
}

// hasCode compares only owned bounded errors, never filesystem text.
func hasCode(err error, code string) bool { var e *Error; return errors.As(err, &e) && e.Code == code }

// readFile verifies on-disk size and a sentinel, preventing corrupt entries from bypassing upload bounds.
func (s *Store) readFile(ctx context.Context, name string) ([]byte, error) {
	if e := checkContext(ctx); e != nil {
		return nil, e
	}
	f, e := s.safeOpen(name, os.O_RDONLY)
	if e != nil {
		return nil, e
	}
	defer f.Close()
	info, e := f.Stat()
	if e != nil || info.Size() < 1 || info.Size() > MaxBytes {
		return nil, failure("unsafe_storage")
	}
	raw, e := io.ReadAll(io.LimitReader(f, MaxBytes+1))
	if e != nil || len(raw) != int(info.Size()) || len(raw) > MaxBytes {
		return nil, failure("storage_error")
	}
	if e = checkContext(ctx); e != nil {
		return nil, e
	}
	return raw, nil
}

// receipt computes metadata from actual bytes, never a caller digest or filename.
func receipt(r Reference, raw []byte) Receipt { return Receipt{r, len(raw), sha256.Sum256(raw)} }

// closeSource owns cleanup even when the read context has already expired.
func closeSource(source Source) error {
	ctx, cancel := context.WithTimeout(context.Background(), time.Second)
	defer cancel()
	if e := source.Close(ctx); e != nil {
		return failure("source_error")
	}
	return nil
}

// consume enforces the sentinel cap and rejects unproductive or malformed Source implementations.
func consume(ctx context.Context, source Source) ([]byte, error) {
	raw := make([]byte, 0, 32*1024)
	empty := 0
	for {
		if e := checkContext(ctx); e != nil {
			return nil, e
		}
		var buf [32 * 1024]byte
		want := min(len(buf), MaxBytes+1-len(raw))
		n, e := source.Read(ctx, buf[:want])
		if n < 0 || n > want {
			return nil, failure("source_error")
		}
		if n > 0 {
			raw = append(raw, buf[:n]...)
			empty = 0
		} else {
			empty++
		}
		if len(raw) > MaxBytes {
			return nil, failure("too_large")
		}
		if e != nil {
			if errors.Is(e, io.EOF) {
				break
			}
			if ctx.Err() != nil {
				return nil, failure("cancelled")
			}
			return nil, failure("source_error")
		}
		if empty >= 100 {
			return nil, failure("source_error")
		}
	}
	if e := checkContext(ctx); e != nil {
		return nil, e
	}
	if len(raw) == 0 {
		return nil, failure("empty_object")
	}
	return raw, nil
}

// Put publishes immutable exact bytes; after publication starts, uncertain outcomes require retry of the same reference.
func (s *Store) Put(parent context.Context, r Reference, source Source) (out Receipt, err error) {
	if source == nil {
		return out, failure("source_error")
	}
	closed := false
	defer func() {
		if !closed {
			if e := closeSource(source); err == nil && e != nil {
				out = Receipt{}
				err = e
			}
		}
	}()
	if !validReference(r) {
		return out, failure("invalid_reference")
	}
	ctx, cancel := context.WithTimeout(parent, 15*time.Second)
	defer cancel()
	s.life.RLock()
	defer s.life.RUnlock()
	if s.closed {
		return out, failure("storage_closed")
	}
	raw, e := consume(ctx, source)
	if e != nil {
		return out, e
	}
	e = closeSource(source)
	closed = true
	if e != nil {
		return out, e
	}
	if e = checkContext(ctx); e != nil {
		return out, e
	}
	id, e := randomID()
	if e != nil {
		return out, e
	}
	temp := "tmp_" + id
	f, e := s.create(temp)
	if e != nil {
		return out, failure("storage_error")
	}
	defer func() { _ = f.Close(); _ = s.root.Remove(temp) }()
	if _, e = f.Write(raw); e != nil {
		return out, failure("storage_error")
	}
	if e = s.checkpoint("before_file_sync"); e != nil {
		return out, e
	}
	if e = f.Sync(); e != nil {
		return out, failure("storage_error")
	}
	if e = f.Close(); e != nil {
		return out, failure("storage_error")
	}
	if e = s.checkpoint("before_publish"); e != nil {
		return out, e
	}
	key := stem(r)
	unlock, e := s.lock(ctx, key)
	if e != nil {
		return out, e
	}
	defer unlock()
	if e = checkContext(ctx); e != nil {
		return out, e
	}
	deleted, e := s.isDeleted(key)
	if e != nil {
		return out, e
	}
	if deleted {
		return out, failure("object_deleted")
	}
	existing, e := s.readFile(ctx, key+".data")
	if e == nil {
		if !bytes.Equal(existing, raw) {
			return out, failure("object_conflict")
		}
		if e = s.syncDirectory(); e != nil {
			return out, failure("storage_unknown")
		}
		if ctx.Err() != nil {
			return out, failure("storage_unknown")
		}
		return receipt(r, existing), nil
	}
	if !hasCode(e, "not_found") {
		return out, e
	}
	if e = checkContext(ctx); e != nil {
		return out, e
	}
	if e = s.root.Link(temp, key+".data"); e != nil {
		return out, failure("storage_unknown")
	}
	if e = s.checkpoint("after_publish"); e != nil {
		return out, failure("storage_unknown")
	}
	if e = s.syncDirectory(); e != nil {
		return out, failure("storage_unknown")
	}
	if ctx.Err() != nil {
		return out, failure("storage_unknown")
	}
	return receipt(r, raw), nil
}

// Read returns a bounded private copy only while the current reference is not tombstoned.
func (s *Store) Read(parent context.Context, r Reference) ([]byte, Receipt, error) {
	if !validReference(r) {
		return nil, Receipt{}, failure("invalid_reference")
	}
	ctx, cancel := context.WithTimeout(parent, 15*time.Second)
	defer cancel()
	s.life.RLock()
	defer s.life.RUnlock()
	if s.closed {
		return nil, Receipt{}, failure("storage_closed")
	}
	unlock, e := s.lock(ctx, stem(r))
	if e != nil {
		return nil, Receipt{}, e
	}
	defer unlock()
	deleted, e := s.isDeleted(stem(r))
	if e != nil {
		return nil, Receipt{}, e
	}
	if deleted {
		return nil, Receipt{}, failure("object_deleted")
	}
	raw, e := s.readFile(ctx, stem(r)+".data")
	if e != nil {
		return nil, Receipt{}, e
	}
	return raw, receipt(r, raw), nil
}

// Delete makes a permanent tombstone before unlinking bytes, including references not yet uploaded.
func (s *Store) Delete(parent context.Context, r Reference) error {
	if !validReference(r) {
		return failure("invalid_reference")
	}
	ctx, cancel := context.WithTimeout(parent, 15*time.Second)
	defer cancel()
	s.life.RLock()
	defer s.life.RUnlock()
	if s.closed {
		return failure("storage_closed")
	}
	key := stem(r)
	unlock, e := s.lock(ctx, key)
	if e != nil {
		return e
	}
	defer unlock()
	if e = checkContext(ctx); e != nil {
		return e
	}
	deleted, e := s.isDeleted(key)
	if e != nil {
		return e
	}
	// Validate a present data inode before creating a deletion marker; never follow a substituted symlink.
	data, e := s.safeOpen(key+".data", os.O_RDONLY)
	if e == nil {
		_ = data.Close()
	} else if !hasCode(e, "not_found") {
		return e
	}
	if !deleted {
		id, e := randomID()
		if e != nil {
			return e
		}
		temp := "tmp_" + id
		f, e := s.create(temp)
		if e != nil {
			return failure("storage_error")
		}
		defer func() { _ = f.Close(); _ = s.root.Remove(temp) }()
		if e = f.Sync(); e != nil {
			return failure("storage_error")
		}
		if e = f.Close(); e != nil {
			return failure("storage_error")
		}
		if e = checkContext(ctx); e != nil {
			return e
		}
		if e = s.root.Link(temp, key+".deleted"); e != nil {
			return failure("storage_unknown")
		}
		if e = s.checkpoint("after_tombstone"); e != nil {
			return failure("storage_unknown")
		}
	}
	if e = s.syncDirectory(); e != nil {
		return failure("storage_unknown")
	}
	if e = checkContext(ctx); e != nil {
		return failure("storage_unknown")
	}
	if e = s.root.Remove(key + ".data"); e != nil && !errors.Is(e, os.ErrNotExist) {
		return failure("storage_unknown")
	}
	if e = s.checkpoint("after_delete"); e != nil {
		return failure("storage_unknown")
	}
	if e = s.syncDirectory(); e != nil {
		return failure("storage_unknown")
	}
	if ctx.Err() != nil {
		return failure("storage_unknown")
	}
	return nil
}
